class Command(BaseCommand):
    help = 'Наполняет БД демо-контентом: 6 категорий, 12 шаблонов, 5 статей (идемпотентно)'

    def handle(self, *args, **options):
        # Категории
        cat_map = {}
        for data in CATEGORIES:
            obj, created = Category.objects.get_or_create(
                slug=data['slug'], defaults=data
            )
            cat_map[data['slug']] = obj
            self.stdout.write(
                f'{"+" if created else "="} Категория: {obj.name}'
            )

        # Шаблоны промптов
        for slug, name, system_prompt, user_tpl in TEMPLATES:
            obj, created = PromptTemplate.objects.get_or_create(
                category=cat_map[slug],
                name=name,
                defaults={
                    'system_prompt': system_prompt,
                    'user_prompt_template': user_tpl,
                    'variables': VARS_BASE,
                    'is_active': True,
                },
            )
            self.stdout.write(
                f'{"+" if created else "="} Шаблон: [{obj.category.name}] {obj.name}'
            )

        # Статьи гайдбука
        for data in ARTICLES:
            obj, created = GuideArticle.objects.get_or_create(
                slug=data['slug'], defaults=data
            )
            self.stdout.write(
                f'{"+" if created else "="} Статья: {obj.title}'
            )

        self.stdout.write(self.style.SUCCESS('\nНаполнение БД завершено.'))
